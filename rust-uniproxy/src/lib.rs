// В Rust проекты организованы как:
// - binary crate (src/main.rs) - исполняемый файл
// - library crate (src/lib.rs) - переиспользуемая библиотека
//
// Мы используем оба: main.rs использует библиотеку из lib.rs
//
// ============================================================================

// Объявляем публичные модули
// pub mod - делает модуль доступным вне crate
// В Go эквивалент: package config (автоматически публичный)
//
// Модули могут быть:
// 1. В отдельном файле: src/config.rs
// 2. В директории с mod.rs: src/config/mod.rs
// Мы используем второй вариант для модулей с подмодулями

pub mod config;   // Конфигурация из environment variables
pub mod server;   // HTTP сервер с Axum
pub mod health;   // Health checking логика
pub mod metrics;  // Prometheus метрики

// ============================================================================
// ВАЖНО: МОДУЛЬНАЯ СИСТЕМА RUST VS GO
// ============================================================================
//
// GO:
// - Пакеты определяются директориями
// - package config в начале файла
// - Экспорт через заглавные буквы (Config, Load)
// - Импорт: import "github.com/user/repo/pkg/config"
//
// RUST:
// - Модули определяются явно через pub mod
// - Иерархия модулей: crate::config::types::Config
// - Экспорт через pub keyword
// - Импорт: use crate::config::Config;
//
// ============================================================================
